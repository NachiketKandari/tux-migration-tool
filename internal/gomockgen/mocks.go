package gomockgen

import (
	"context"
	"os"
	"os/exec"
	"path/filepath"

	"tux-migration-tool/internal/telemetry"
)

// MockTarget names one interface to regenerate with mockgen.
type MockTarget struct {
	Source string // interface file path
	Dest   string // mock output path
	Name   string // interface name
	// Gomock names the gomock implementation the generated mock must import,
	// or "" for the uber-go default. It is a per-target field rather than a
	// package global because a converted service inherits its host module's
	// dependencies: the tree that vendors github.com/golang/mock needs a mock
	// in that same major, and a package cannot hold both
	// (go.uber.org/mock/gomock and github.com/golang/mock/gomock declare
	// distinct types, so one mock satisfies neither controller).
	Gomock string
}

// MockTargetsFor derives the standard db/controller mock targets (A4.3) —
// the one table for the artifact conventions (mock_store.go /
// mock_controller.go, `<Service>Store` / `<Service>Controller`). Paths that
// do not exist are omitted (gentest best-effort semantics); convert passes
// existence through to RunMocks, so the filter is harmless there.
func MockTargetsFor(serviceDir, service string) []MockTarget {
	return []MockTarget{
		{
			Source: filepath.Join(serviceDir, "db", "interface.go"),
			Dest:   filepath.Join(serviceDir, "db", "mock_store.go"),
			Name:   service + "Store",
		},
		{
			Source: filepath.Join(serviceDir, "controller", "interface.go"),
			Dest:   filepath.Join(serviceDir, "controller", "mock_controller.go"),
			Name:   service + "Controller",
		},
	}
}

// mockgenVersion pins the uber-go/mock release the go-run fallback uses
// when no mockgen binary is on PATH (verified against v0.6.0). Pinned,
// never floating: the generated mocks must match the gomock runtime the
// target module vendors, and a floating tag would move under us.
const mockgenVersion = "v0.6.0"

// legacyMockgenVersion pins the archived github.com/golang/mock line, used
// when the scanned module vendors that major instead. Same reasoning as
// mockgenVersion: a mock generated by one major will not satisfy a
// gomock.NewController from the other, so the version must be a fixed,
// known-good one rather than whatever @latest resolves to today.
const legacyMockgenVersion = "v1.6.0"

// LegacyGomockPath is the archived gomock module the templates import. It is
// exported so callers can detect a tree that vendors this major and ask for
// a mock generated in it (MockTarget.Gomock).
const LegacyGomockPath = "github.com/golang/mock"

// RunMocks regenerates the gomock doubles for targets, in whichever major the
// target tree vendors (MockTarget.Gomock; empty means the uber-go default).
// The mockgen binary wins when present (fast, offline); otherwise the run
// falls back to `go run <mockgen>@<pinned>` so generation never depends on
// machine setup — it is one command either way. Missing sources are skipped
// silently; any other failure is best-effort (WARN, never fatal). Shared by
// `convert` and `gentest` (PRD-2026-09-09 GT-D7).
func RunMocks(ctx context.Context, targets []MockTarget) {
	log := telemetry.Log(ctx)
	var live []MockTarget
	for _, t := range targets {
		if _, err := os.Stat(t.Source); err != nil {
			continue
		}
		live = append(live, t)
	}
	if len(live) == 0 {
		return
	}
	// A mockgen on PATH is a single binary whose major we cannot inspect, so
	// it is trusted only for the default (uber-go) generation. Asking for the
	// archived major deliberately bypasses it and goes through the pinned
	// go-run module, because a binary that emits go.uber.org/mock/gomock into
	// a tree vendoring github.com/golang/mock reproduces the two-majors-in-one-
	// -package break this field exists to prevent.
	binary, err := exec.LookPath("mockgen")
	if err != nil {
		binary = ""
		log.Info("mockgen not on PATH — generating via go run", "module", mockgenModule("")+"@"+mockgenVersionFor(""))
	}
	for _, t := range live {
		cmd := mockgenCmd(binary, t)
		if out, cerr := cmd.CombinedOutput(); cerr != nil {
			log.Warn("mockgen failed (best-effort)", "interface", t.Name, "output", string(out))
		} else {
			log.Info("mocks generated", "interface", t.Name, "path", t.Dest)
		}
	}
}

// mockgenVersionFor returns the pinned mockgen release for a gomock major.
func mockgenVersionFor(major string) string {
	if major == LegacyGomockPath {
		return legacyMockgenVersion
	}
	return mockgenVersion
}

// mockgenModule returns the mockgen module path for a gomock major.
func mockgenModule(major string) string {
	if major == LegacyGomockPath {
		return LegacyGomockPath + "/mockgen"
	}
	return "go.uber.org/mock/mockgen"
}

// mockgenCmd builds the mock regeneration command for one target: the local
// binary when it can be trusted for this target's major, else the pinned
// go-run fallback with identical generation flags.
func mockgenCmd(binary string, t MockTarget) *exec.Cmd {
	args := []string{"-source", t.Source, "-destination", t.Dest, "-package", filepath.Base(filepath.Dir(t.Dest)), t.Name}
	if binary != "" && t.Gomock == "" {
		return exec.Command(binary, args...)
	}
	return exec.Command("go", append([]string{"run", mockgenModule(t.Gomock) + "@" + mockgenVersionFor(t.Gomock)}, args...)...)
}
